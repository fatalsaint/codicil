from . import ticket as ticket_mod

UTC = "%Y-%m-%dT%H:%M:%SZ"
LEDGER_ENTRY_RE = re.compile(r"^## \[L(\d+)\] (\S+) ([^:]+): (.*)$")
LAW_LINE_RE = re.compile(r"^- \[L(\d+)\] (.*) \((maintainer|orchestrator), (\d{4}-\d{2}-\d{2})\)\s*$")
COUNTEREXAMPLE_MARKERS = ("never", "which is", "misread", "counterexample", "incident",
                          "because", "once", "forbidden", "prohibit", "so \"", "so \u201c")
CENSUS_BEGIN = "<!-- BEGIN CODIC CENSUS (generated by `codic board`; do not edit) -->"
CENSUS_END = "<!-- END CODIC CENSUS -->"
DISPATCH_MARK = "<!-- codic:dispatch v1 ticket={tid} -->"


def now_utc() -> str:
    return datetime.now(timezone.utc).strftime(UTC)


def today() -> str:
    return now_utc()[:10]


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text)
    tmp.replace(path)


# -- ledger -----------------------------------------------------------------
def ledger_next_id(f) -> int:
    ids = [int(m.group(1)) for line in _lines(f.ledger_path)
           if (m := LEDGER_ENTRY_RE.match(line))]
    return (max(ids) + 1) if ids else 1


def ledger_append(f, role: str, title: str, body: str = "", supersedes: str = "") -> str:
    lid = f"L{ledger_next_id(f)}"
    entry = f"\n## [{lid}] {now_utc()} {role}: {title}\n"
    if body:
        entry += body.rstrip() + "\n"
    if supersedes:
        s = supersedes if supersedes.startswith("L") else f"L{supersedes}"
        entry += f"Supersedes: [{s}]\n"
    with open(f.ledger_path, "a") as fh:
        fh.write(entry)
    return lid


def ledger_entries(f) -> list[dict]:
    out = []
    cur = None
    for line in _lines(f.ledger_path):
        m = LEDGER_ENTRY_RE.match(line)
        if m:
            cur = {"id": f"L{m.group(1)}", "ts": m.group(2), "role": m.group(3),
                   "title": m.group(4), "body": []}
            out.append(cur)
        elif cur is not None:
            cur["body"].append(line)
    return out


def ledger_ids(f) -> set[str]:
    return {e["id"] for e in ledger_entries(f)}


# -- prefix hash chain (I3) ---------------------------------------------------
def chain_checkpoint(f, path: Path) -> None:
    f.chain_dir.mkdir(parents=True, exist_ok=True)
    data = path.read_bytes()
    cp = f.chain_dir / (path.name + ".sha")
    cp.write_text(f"{hashlib.sha256(data).hexdigest()} {len(data)} {now_utc()}\n")


def chain_verify(f, path: Path) -> tuple[bool, str]:
    """True if `path` still begins with the last checkpointed prefix."""
    cp = f.chain_dir / (path.name + ".sha")
    if not cp.exists():
        return True, "no checkpoint yet"
    if not path.exists():
        return False, "file vanished after checkpoint"
    want_sha, want_len, _ = cp.read_text().split()
    head = path.read_bytes()[: int(want_len)]
    if hashlib.sha256(head).hexdigest() != want_sha:
        return False, f"prefix changed after checkpoint (first {want_len} bytes rewritten)"
    return True, "append-only holds"


# -- law ----------------------------------------------------------------------
def law_lines(f) -> list[dict]:
    """Parse the `## Law` section of STATE.md into structured lines."""
    text = _read(f.law_path)
    m = re.search(r"^## Law\s*$(.*?)(?=^## |\Z)", text, re.M | re.S)
    if not m:
        return []
    out = []
    for line in m.group(1).splitlines():
        if not line.strip():
            continue
        lm = LAW_LINE_RE.match(line.strip())
        if lm:
            out.append({"cite": f"L{lm.group(1)}", "text": lm.group(2),
                        "owner": lm.group(3), "date": lm.group(4), "raw": line.strip(),
                        "ok_shape": True})
        else:
            out.append({"raw": line.strip(), "ok_shape": False})
    return out


def law_section_text(f) -> str:
    text = _read(f.law_path)
    m = re.search(r"^## Law\s*$(.*?)(?=^## |\Z)", text, re.M | re.S)
    return m.group(1) if m else ""


def law_add(f, owner: str, cite: str, text: str, force: bool = False) -> str:
    low = text.lower()
    if not force and not any(k in low for k in COUNTEREXAMPLE_MARKERS):
        raise SystemExit(
            "law lines must carry the clause that names their own misreading (SPEC 4.2): "
            "include a counterexample clause ('never ...', 'which is the misreading ...', "
            "an incident, a cause). Re-run with --force only if the clause is present in other words.")
    c = cite if cite.startswith("L") else f"L{cite}"
    line = f"- [{c}] {text} ({owner}, {today()})"
    cur = f.law_path.read_text()
    m = re.search(r"^## Census\b", cur, re.M)
    if m:
        new = cur[: m.start()].rstrip() + "\n" + line + "\n\n" + cur[m.start():]
    else:
        new = cur.rstrip() + "\n" + line + "\n"
    atomic_write(f.law_path, new)
    return line


def has_counterexample(text: str) -> bool:
    low = text.lower()
    return any(k in low for k in COUNTEREXAMPLE_MARKERS)


# -- census section -------------------------------------------------------------
def set_census(f, census_md: str) -> None:
    text = _read(f.law_path)
    body = f"{CENSUS_BEGIN}\n{census_md.rstrip()}\n{CENSUS_END}\n"
    if CENSUS_BEGIN in text:
        text = re.sub(re.escape(CENSUS_BEGIN) + r".*?" + re.escape(CENSUS_END),
                      lambda _: body.rstrip(), text, flags=re.S)
    else:
        text = text.rstrip() + "\n\n## Census\ngenerated by `codic board`; do not edit\n\n" + body
    atomic_write(f.law_path, text if text.endswith("\n") else text + "\n")


def census_text(f) -> str:
    text = _read(f.law_path)
    i, j = text.find(CENSUS_BEGIN), text.find(CENSUS_END)
    if i < 0 or j < 0:
        return ""
    return text[i + len(CENSUS_BEGIN):j].strip()


# -- roster ---------------------------------------------------------------------
def roster_load(f) -> dict:
    if f.roster_path.exists():
        return json.loads(f.roster_path.read_text())
    return {}


def roster_save(f, roster: dict) -> None:
    atomic_write(f.roster_path, json.dumps(roster, indent=1, sort_keys=True) + "\n")


# -- resources (SPEC 6.4) ---------------------------------------------------------
def resource_state(f) -> dict:
    """Marker directory presence is the window state; holder lives in the marker."""
    out = {}
    if f.resources_dir.exists():
        for marker in sorted(f.resources_dir.glob("*.open")):
            holder = marker.read_text().strip() or "unknown"
            out[marker.name[: -len(".open")]] = {"open": True, "holder": holder}
    return out


# -- gates --------------------------------------------------------------------------
def pins_load(f) -> dict:
    if not f.pins_path.exists():
        return {}
    import tomllib
    with open(f.pins_path, "rb") as fh:
        return tomllib.load(fh)


def gate_results(f) -> dict:
    out = {}
    rd = f.gates_dir / "results"
    if rd.exists():
        for j in sorted(rd.glob("*.json")):
            out[j.stem] = json.loads(j.read_text())
    return out


# -- scenarios ------------------------------------------------------------------------
SCENARIO_RE = re.compile(r"^(?:id|status|designated|title):\s*(.*)$", re.M)


def scenarios_load(f) -> list[dict]:
    out = []
    if not f.scenarios.exists():
        return out
    for p in sorted(f.scenarios.glob("*.md")):
        text = p.read_text()
        meta = {}
        for key in ("id", "title", "status", "designated"):
            m = re.match(rf"^{key}:\s*(.*)$", text, re.M)
            if m:
                meta[key] = m.group(1).strip().strip("\"'")
        preds = re.findall(r"```predicate\n(.*?)```", text, re.S)
        meta["path"] = str(p)
        meta["predicates"] = [ln.strip() for blk in preds for ln in blk.splitlines() if ln.strip()]
        out.append(meta)
    return out


# -- dispatch ---------------------------------------------------------------------------
def dispatch_render(f, t: dict, delta: str, budget: str, agent: str = "") -> str:
    """SPEC 6.6: ticket id + delta + budget declaration. Never the ticket body.
    The Report footer is part of the handoff: a worker that finishes silently
    is indistinguishable from a dead one, and the watchdog backstop burns the
    full interval on every early finish."""
    read = [".codic/state/STATE.md", f".codic/state/skills/{t['role']}.md",
            f".codic/state/queue/{t['_state']}/{Path(t['_path']).name}"]
    lines = [DISPATCH_MARK.format(tid=t["id"]),
             f"Ticket: {t['id']} — {t['title']}",
             f"Role: {t['role']}  Worktree: {t.get('worktree', '(none)')}  Engine: {t.get('engine', '(n/a)')}",
             f"Delta: {delta}",
             f"Budget: {budget}",
             "Read (nothing else): " + ", ".join(read),
             f"Report before your final turn: codic report {t['id']} done|blocked "
             f"--as {agent or '<your-slot>'} \"<one line, with evidence path>\" "
             "(wakes the orchestrator and disarms the watchdog)"]
    return "\n".join(lines) + "\n"


def dispatch_check_size(f, text: str, where: str) -> list[str]:
    from .config import BUDGET_DISPATCH
    n = f.tokens(text)
    if n > BUDGET_DISPATCH:
        return [f"{where}: {n} tokens exceeds dispatch budget {BUDGET_DISPATCH}"]
    return []


# -- misc -----------------------------------------------------------------------------
def _read(p: Path) -> str:
    return p.read_text() if p.exists() else ""


def _lines(p: Path) -> list[str]:
    return _read(p).splitlines()


def git(cwd: Path, *args: str, check: bool = True) -> str:
    r = subprocess.run(["git", *args], cwd=str(cwd), capture_output=True, text=True)
    if check and r.returncode != 0:
        raise SystemExit(f"git {' '.join(args)} failed: {r.stderr.strip()}")
    return r.stdout.strip()
